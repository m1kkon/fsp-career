import {createHash} from 'node:crypto';
import {readFileSync,writeFileSync,mkdirSync,rmSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';

export function versionClientAssets(root=fileURLToPath(new URL('../',import.meta.url))){
 const directory=resolve(root,'public/assets');
 rmSync(directory,{recursive:true,force:true});mkdirSync(directory,{recursive:true});
 const urls={};
 const publish=(name,content)=>{
  const hash=createHash('sha256').update(content).digest('hex').slice(0,16);
  const dot=name.lastIndexOf('.'),filename=name.slice(0,dot)+'.'+hash+name.slice(dot);
  writeFileSync(resolve(directory,filename),content);urls[name]='/assets/'+filename;
 };
 for(const name of ['styles.css','enterprise.css','marketplace.css','mvp.css','resume-editor.css','product.css','resume-history.mjs'])publish(name,readFileSync(resolve(root,'public',name)));
 const client=readFileSync(resolve(root,'public/mvp.js'),'utf8').replace("'./resume-history.mjs'",JSON.stringify(urls['resume-history.mjs']));
 publish('mvp.js',readFileSync(resolve(root,'public/assessments.js'),'utf8')+'\n'+client);
 writeFileSync(resolve(root,'app/asset-urls.ts'),'// Generated by scripts/version-client-assets.mjs.\nexport const assetUrls='+JSON.stringify(urls,null,2)+' as const;\n');
 return urls;
}
